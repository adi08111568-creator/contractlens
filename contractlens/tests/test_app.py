"""Functional tests for the Streamlit app using Streamlit's AppTest harness (no browser, no network).

Run:  python tests/test_app.py   (or pytest)

Cache-dependent behaviour is tested on a THROWAWAY COPY of the project with fixture runs generated by the
scripted mock. Fixtures never touch the real data/cache folder, which must stay reserved for real Gemini runs.
"""
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.pop("GEMINI_API_KEY", None)
os.environ.pop("GOOGLE_API_KEY", None)

from streamlit.testing.v1 import AppTest  # noqa: E402

from agent.agent import run_agent          # noqa: E402
from agent.doc import load_contract        # noqa: E402
from agent.mock_llm import MockLLM         # noqa: E402

KEY = json.loads((ROOT / "data" / "ground_truth.json").read_text())


def texts(elements):
    return " | ".join(str(getattr(e, "value", "")) for e in elements)


def new_app(path=ROOT / "app.py"):
    at = AppTest.from_file(str(path), default_timeout=120)
    at.run()
    assert not at.exception, [e.value for e in at.exception]
    return at


def metric_map(at):
    return {m.label: m.value for m in at.metric}


def test_real_cache_folder_is_reserved_for_real_runs():
    cache = ROOT / "data" / "cache" / "agent"
    for p in (list(cache.glob("*.json")) if cache.exists() else []):
        assert json.loads(p.read_text()).get("model") != "scripted-simulation", p


def test_cold_start_defaults_to_labelled_simulation_and_shows_rules_baseline():
    at = new_app()
    assert at.sidebar.radio(key="mode").value.startswith("Scripted simulation")
    assert any("not an AI" in w.value for w in at.sidebar.warning)
    m = metric_map(at)
    assert m["Rules baseline"] == "59.2%" and m["Agent"] == "not run yet"
    assert "$160,000" in m["Manual cost / year"] and m["With agent / year"] == "$7,800"
    assert m["Net savings / year"] == "$152,200"


def test_simulation_run_shows_results_trace_and_banner():
    at = new_app()
    at.selectbox(key="sample").set_value("contract_18")
    at.button(key="run").click().run()
    assert not at.exception, [e.value for e in at.exception]
    assert any("not an AI model" in w.value for w in at.warning)          # banner stays with the result
    m = metric_map(at)
    assert m["Auto-accepted fields"] == "12 / 12" and int(m["Issues caught & fixed"]) >= 2
    assert m["Correct vs answer key"] == "12 / 12"
    assert len(at.dataframe) >= 1


def test_live_mode_without_key_gives_clear_error_not_a_crash():
    at = new_app()
    at.sidebar.radio(key="mode").set_value("Live agent (Gemini)").run()
    at.button(key="run").click().run()
    assert not at.exception
    assert any("No Gemini API key" in e.value for e in at.error), texts(at.error)


def test_replay_mode_without_saved_run_warns():
    at = new_app()
    at.sidebar.radio(key="mode").set_value("Replay saved run (real Gemini output)").run()
    at.button(key="run").click().run()
    assert not at.exception
    assert any("No saved run" in w.value for w in at.warning), texts(at.warning)


def test_with_saved_runs_replay_accuracy_review_and_impact_work():
    tmp = Path(tempfile.mkdtemp())
    try:
        proj = tmp / "proj"
        shutil.copytree(ROOT, proj, ignore=shutil.ignore_patterns("*.zip", "__pycache__", ".git"))
        out = proj / "data" / "cache" / "agent"
        out.mkdir(parents=True, exist_ok=True)
        for i, cid in enumerate(sorted(KEY)[:6]):                          # FIXTURE runs from the scripted mock
            doc = load_contract(ROOT / "data" / "contracts" / "pdf" / f"{cid}.pdf")
            flag = "governing_law" if i % 2 == 0 else None                 # some fields go to human review
            res = run_agent(doc, MockLLM(doc, KEY[cid]["truth"], flag_field=flag))
            (out / f"{cid}.json").write_text(json.dumps({**res, "model": "fixture"}, default=str))

        at = new_app(proj / "app.py")
        assert at.sidebar.radio(key="mode").value.startswith("Replay")      # cache present -> replay by default
        m = metric_map(at)
        # 3 of 6 contracts had one field flagged for a human -> unanswered counts as wrong: (72-3)/72 = 95.8%
        assert m["Agent"] == "95.8%" and m["Agent contracts scored"] == "6"

        # replay one saved run
        at.selectbox(key="sample").set_value(sorted(KEY)[0])
        at.toggle(key="animate").set_value(False)
        at.button(key="run").click().run()
        assert not at.exception, [e.value for e in at.exception]
        assert "model `fixture`" in texts(at.caption)

        # review queue lists the flagged fields (3 contracts x 1 flagged field)
        m = metric_map(at)
        assert m["Fields needing a human"].startswith("3") and m["Contracts processed"] == "6"

        # impact tab offers the measured basis once saved runs exist
        labels = at.radio(key="basis").options
        assert any(o.startswith("Measured from 6 saved agent runs") for o in labels), labels
        at.radio(key="basis").set_value([o for o in labels if o.startswith("Measured")][0]).run()
        assert not at.exception, [e.value for e in at.exception]
        assert metric_map(at)["Net savings / year"] != "$152,200"          # review share changed the answer
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def test_dollar_amounts_are_escaped_so_markdown_does_not_render_math():
    at = new_app()
    line = next(m.value for m in at.markdown if m.value.startswith("Per contract:"))
    assert "\\$16.00" in line and "\\$0.78" in line, line               # two bare $ in one line would become a formula
    at.toggle(key="rec_on").set_value(True).run()
    ok = next(s.value for s in at.success if "recovery benefit" in s.value)
    assert "\\$250,000" in ok, ok


def test_impact_inputs_flow_through():
    at = new_app()
    at.number_input(key="vol").set_value(20000).run()
    assert metric_map(at)["Manual cost / year"] == "$320,000"
    at.toggle(key="rec_on").set_value(True).run()
    assert not at.exception and any("recovery benefit" in s.value for s in at.success)


